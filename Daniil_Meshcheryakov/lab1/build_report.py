import re

import pandas as pd
from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Cm, Pt

d = pd.read_csv("outputs/transformed_texts.csv")
doc = Document()
st = doc.styles["Normal"]
st.font.name, st.font.size = "Times New Roman", Pt(12)
for s in doc.sections:
    s.left_margin = s.right_margin = Cm(2)

words = []


def p(text, bold=False, align=None):
    par = doc.add_paragraph()
    run = par.add_run(text)
    run.bold = bold
    if align:
        par.alignment = align
    words.append(text)
    return par


def h(text):
    doc.add_heading(text, level=2)
    words.append(text)


def fig(path, caption):
    doc.add_picture(path, width=Cm(17))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    p(caption, align=WD_ALIGN_PARAGRAPH.CENTER)


doc.add_heading("Лабораторная работа №1. Один текст - разные представления", level=1)
p("Курс: Автоматическая обработка текстов")
p("Автор: Мещеряков Даниил Павлович (ИСУ 409130)")
p("Преподаватель: Гусарова Наталия Федоровна")

h("1. Данные")
p("Официальный репозиторий RuSentiment больше не содержит корпус (он удален по требованию VK), поэтому "
  "я использую оригинальный файл rusentiment_preselected_posts.csv с зеркала Hugging Face. В нем 6950 постов "
  "и пять классов: neutral (2977), positive (1475), negative (1360), skip (904), speech (234). Столбец id "
  "я добавляю как номер строки. Буква «е» с точками и длинные тире приведены к «е» и дефису.")
p("Пропусков и пустых текстов нет, точных дубликатов тоже нет. После приведения к нижнему регистру и "
  "схлопывания пробелов находится 8 повторов (например, «Как-то так» и «как-то так», «Сессия закрыта!»). "
  "Для работы я беру стратифицированную выборку: по 30 текстов каждого класса, 150 текстов, random_state = 409130; "
  "повторов в ней нет.")
p("Распределение длин сильно скошено вправо: медиана 10 слов, среднее около 19, максимум 134. Самые короткие "
  "тексты у positive (медиана 7 слов), самые длинные у speech (медиана 20): поздравления обычно развернутые. "
  "Для BoW и TF-IDF это значит, что большинство векторов содержит всего 5-15 ненулевых координат.")
fig("outputs/length_distribution.png", "Рис. 1. Распределение длин текстов")

h("2. Представления")
p("Токенизацию я выполняю с помощью razdel, стоп-слова не удаляю: частица «не» здесь смыслообразующая. "
  "Я строю четыре представления: 13 поверхностных признаков (длина в символах, словах и предложениях, "
  "доля заглавных букв, число «!», «?», многоточий, эмодзи, смайликов, отрицаний и т.д.); bag-of-words "
  "(CountVectorizer, словарь 1564 слова, разреженность 98.9%); TF-IDF; sentence embeddings двух моделей: "
  "paraphrase-multilingual-MiniLM-L12-v2 и rubert-tiny2. Векторизаторы я обучаю на выборке вместе с "
  "девятью измененными текстами, чтобы слова парафразов не выпадали из словаря.")
p("Класс тональности ни одно представление само по себе почти не отражает: среднее косинусное сходство "
  "внутри класса лишь немного выше, чем между классами (BoW 0.048 против 0.043, MiniLM 0.362 против 0.327).")

h("3. Девять сравнений")
p("Для сравнения я беру три текста разных классов: positive «Хочется лета. Тупо болтаться на улице...», negative "
  "«В школе на первых двух уроках хочется спать. На третьем - есть. А на остальных просто здохнуть..», "
  "neutral «Купили ребенку селфи-палку, так он теперь везде ее таскает и фигачит луки...». Для каждого "
  "я составляю перестановку, парафраз и смысловое изменение (добавляю «не» в positive, заменяю «здохнуть» "
  "на «учиться» в negative, заменяю «везде ее таскает» на «нигде ее не таскает и не фигачит» в neutral). "
  "Полные тексты и обоснования приведены в transformed_texts.csv.")

cols = ["BoW", "TF-IDF", "emb_MiniLM", "emb_rubert_tiny2"]
t = doc.add_table(rows=1, cols=7)
t.style = "Light Grid Accent 1"
for c, name in zip(t.rows[0].cells, ["Текст", "Преобразование", "Смысл изменен?", "BoW", "TF-IDF", "MiniLM", "rubert-tiny2"]):
    c.text = name
for _, r in d.iterrows():
    cells = t.add_row().cells
    vals = [r.label, r.transformation, r.meaning_changed] + [f"{r[c]:.3f}" for c in cols]
    for c, v in zip(cells, vals):
        c.text = v
for row in t.rows:
    for c in row.cells:
        for par in c.paragraphs:
            for run in par.runs:
                run.font.size = Pt(10)
p("Таблица 1. Косинусное сходство исходного и измененного текста", align=WD_ALIGN_PARAGRAPH.CENTER)

p("Моя ручная оценка: перестановки и парафразы смысл сохраняют (в русском порядок слов свободный, эллипсис "
  "«На третьем - есть» остается понятным; перестановка предложений в neutral немного ухудшает связность, "
  "но факты те же). Все три смысловых изменения смысл меняют: желание превращается в нежелание, жалоба "
  "теряет кульминацию, а подарок из полезного становится ненужным.")
fig("outputs/similarity_bars.png", "Рис. 2. Сходство исходных и измененных текстов по представлениям")

p("Средние по трем текстам: перестановка дает 1.000 / 1.000 / 0.974 / 0.982 (BoW / TF-IDF / MiniLM / rubert-tiny2), "
  "парафраз 0.347 / 0.212 / 0.806 / 0.845, смысловое изменение 0.931 / 0.929 / 0.963 / 0.978. Для сравнения, "
  "фоновое сходство со случайным текстом выборки: 0.054 / 0.022 / 0.229 / 0.479.")

h("4. Рассогласование числа и смысла")
p("Во всех 12 сочетаниях «текст × представление» текст с измененным смыслом оказался ближе к исходному, "
  "чем парафраз с тем же смыслом. Наиболее показательные случаи:")
p("1) «Не хочется лета»: одно отрицание переворачивает смысл, но MiniLM дает 0.991, это выше, чем для "
  "безобидной перестановки (0.958). BoW и TF-IDF дают 0.985 и 0.993.")
p("2) Парафраз positive «Скорее бы лето!...»: смысл тот же, но TF-IDF дает 0.063, почти на уровне "
  "фона (0.022), а BoW 0.170. Совпали только служебные слова.")
p("3) «здохнуть» → «учиться»: тональность меняется с негативной на ироничную, но rubert-tiny2 дает 0.989, "
  "а для парафраза с тем же смыслом только 0.867.")
p("4) Контрольные пары «Мать любит дочь» / «Дочь любит мать» и «Курс доллара вырос, а рубль упал» / "
  "«Курс доллара упал, а рубль вырос»: смысл противоположный, BoW дает ровно 1.0, эмбеддинги 0.944-0.999.")

h("5. Выводы")
p("Поверхностные признаки видят длину, пунктуацию и явные маркеры: счетчик отрицаний сработал в positive (+1) "
  "и neutral (+3). Они не видят замену слова (в negative все признаки совпали) и не различают парафраз и "
  "перестановку, если длина похожа.")
p("Bag-of-words видит только, какие слова и сколько раз встретились. Он полностью игнорирует порядок "
  "(перестановка всегда 1.0, даже когда меняются роли) и синонимию, поэтому парафраз для него почти другой "
  "текст. Отрицание он замечает лишь как одно лишнее слово из многих, поэтому сходство падает на 1-15%.")
p("TF-IDF ведет себя так же, но перераспределяет веса: частые слова вроде «на» и «не» получают меньший вес, "
  "а редкие лексические слова больший. Поэтому парафраз оценивается еще ниже, чем в BoW, а короткое "
  "отрицание так же почти не заметно.")
p("Sentence embeddings единственные узнают парафраз (0.78-0.87 при фоне 0.23-0.48) и почти не реагируют "
  "на перестановку. Однако они в основном кодируют тему и лексику, а не истинностное значение: отрицание "
  "и замена ключевого слова снижают сходство лишь на сотые доли. Кроме того, у каждой модели своя шкала "
  "(фон rubert-tiny2 около 0.48), поэтому абсолютные значения косинуса нельзя сравнивать между моделями.")
p("Итог: по моим результатам, ни одно из представлений не дает меры «сохранен ли смысл». Для задач, где важны отрицание или "
  "роли участников (например, анализ тональности), нужны модели, обученные на соответствующем сигнале "
  "(NLI или классификация тональности), а косинусное сходство эмбеддингов стоит считать мерой тематической "
  "близости.")

doc.save("report.docx")

